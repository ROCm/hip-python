"""Guard the hand-maintained ``.pyi`` stub of a handcoded Cython module.

A handful of Cython modules are written by hand rather than emitted by
interfacegen, and their type stubs are committed to git so that
``sphinx-autoapi`` can document them and type checkers can resolve their
signatures without the compiled extensions on ``sys.path``. Most of
those stubs are machine-generated by a developer-run CMake target
(``cmake --build build --target all_stubs``, wrapped by
``ci/docs/regenerate-stubs.sh``).

``cuda.bindings.cufile`` is the exception. Its public surface is almost
entirely module-level ``cpdef`` functions, which stubgen can only render
as opaque ``cython_function_or_method`` attributes, so its ``.pyi`` is
curated by hand and excluded from the target. Nothing but this suite
notices when a ``.pyx`` edit is not mirrored into it.

This suite deliberately does *not* re-run stubgen against the generated
stubs to check them for staleness. That comparison depends on the build
it runs against -- the Cython and mypy versions, and above all whether
the extension was compiled against the CPython limited API, where
Cython loses the per-method docstrings and renames its runtime module --
so it reported failures for correct stubs. The banner every generated
stub carries is what tells a reader not to edit one by hand.

It runs against the *installed* wheels, so the ``.pyi`` it checks is the
artifact users actually consume.
"""

import ast
import importlib
import importlib.util
import inspect
import os

import pytest

#: Handcoded modules whose `.pyi` is maintained by hand because stubgen
#: cannot produce a useful one.
HANDWRITTEN_STUB_MODULES = ["cuda.bindings.cufile"]


def _import_or_skip(module: str):
    """Import `module`, skipping when its wheel is not installed here.

    `cuda.bindings.cufile` is only built when hipFILE is present, which
    it is not on Windows.
    """
    try:
        found = importlib.util.find_spec(module) is not None
    except ModuleNotFoundError:
        # `find_spec` returns None only for a missing leaf; a missing
        # parent package raises, which is what an environment without
        # hip-python-interop installed at all looks like.
        found = False
    if not found:
        pytest.skip(f"{module} is not installed on this platform")
    return importlib.import_module(module)


def _installed_stub_path(mod) -> str:
    """Path of the `.pyi` shipped next to the module's compiled extension."""
    return os.path.join(
        os.path.dirname(mod.__file__), mod.__name__.rsplit(".", 1)[-1] + ".pyi"
    )


def _declared_names(body) -> set:
    """Names bound by a `.pyi` body: defs, classes and annotated attributes."""
    names = set()
    for node in body:
        if isinstance(
            node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)
        ):
            names.add(node.name)
        elif isinstance(node, ast.AnnAssign) and isinstance(
            node.target, ast.Name
        ):
            names.add(node.target.id)
        elif isinstance(node, ast.Assign):
            names.update(t.id for t in node.targets if isinstance(t, ast.Name))
    return names


@pytest.mark.parametrize("module", HANDWRITTEN_STUB_MODULES)
def test_handwritten_stub_covers_public_surface(module):
    """Every public name of a hand-maintained module appears in its stub.

    A byte comparison is meaningless here — the whole point of these stubs
    is that they are better than stubgen's output. What can still be
    checked mechanically is that nothing has been added to or renamed in
    the `.pyx` without being mirrored into the `.pyi`, which is the drift
    that actually reaches users.

    The stub is parsed rather than grepped: a substring search over the
    file text is satisfied by any mention, including one inside an
    unrelated docstring or a longer identifier, so it would pass even
    after a public function was renamed out from under it.
    """
    mod = _import_or_skip(module)
    stub = _installed_stub_path(mod)
    assert os.path.exists(stub), f"{module} ships no {os.path.basename(stub)}"

    with open(stub, encoding="utf-8") as handle:
        tree = ast.parse(handle.read())
    top_level = _declared_names(tree.body)
    class_members = {
        node.name: _declared_names(node.body)
        for node in tree.body
        if isinstance(node, ast.ClassDef)
    }

    missing = []
    for name, obj in vars(mod).items():
        if name.startswith("_"):
            continue
        # Imported modules (`enum`, `os`) are implementation detail, not API.
        if inspect.ismodule(obj):
            continue
        if name not in top_level:
            missing.append(name)
            continue
        if inspect.isclass(obj):
            declared = class_members.get(name, set())
            missing.extend(
                f"{name}.{attr}"
                for attr in vars(obj)
                if not attr.startswith("_") and attr not in declared
            )

    assert not missing, (
        f"{module} exposes names that its hand-maintained stub does not "
        f"declare: {sorted(missing)}. {os.path.basename(stub)} is edited by "
        f"hand — update it in the same commit as the .pyx."
    )
