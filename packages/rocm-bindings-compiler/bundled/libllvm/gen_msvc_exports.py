"""Writes a module-definition file for the LLVM C API found in static archives.

A PE image exports nothing unless the objects were compiled with
``__declspec(dllexport)`` or the linker is handed an explicit list. ROCm's
Windows LLVM is built with the export annotations off (``llvm-config.h`` has
``LLVM_ENABLE_LLVM_EXPORT_ANNOTATIONS`` undefined), so its archives carry no
export directives at all and a ``/WHOLEARCHIVE`` link produces a DLL with no
export table. Naming the symbols in a ``.def`` is the way out, and the C API is
the right subset to name: it is unmangled, stable across toolsets, and it is
what the bindings call. This is the same approach upstream LLVM takes for
``LLVM-C.dll`` in ``llvm/tools/llvm-shlib/gen-msvc-exports.py``.

Listing a symbol in the export list also makes the linker pull in the object
that defines it, so no ``/WHOLEARCHIVE`` is needed on top: the export list
decides what the DLL contains.

Usage:
  gen_msvc_exports.py --nm <llvm-nm> --output <file.def> [--extra NAME]... ARCHIVE...
"""

import argparse
import pathlib
import subprocess
import sys

# MSVC mangles C++ names with a leading '?'; everything else nm reports for
# these archives is either a C entry point or an assembler-level name.
C_API_PREFIX = "LLVM"


def defined_symbols(nm: str, archive: str):
    """Yields (name, is_function) for every externally defined symbol."""
    proc = subprocess.run(
        [nm, "--defined-only", "--extern-only", "--no-sort", archive],
        capture_output=True,
        text=True,
        errors="replace",
    )
    if proc.returncode != 0:
        raise RuntimeError(
            f"{nm} failed on {archive} (exit {proc.returncode}): {proc.stderr.strip()}"
        )
    for line in proc.stdout.splitlines():
        parts = line.split()
        # "<address> <kind> <name>"; archive member headers have no kind column.
        if len(parts) < 3 or len(parts[-2]) != 1:
            continue
        yield parts[-1], parts[-2] == "T"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--nm", required=True, help="llvm-nm executable")
    parser.add_argument(
        "--output", required=True, help="module-definition file to write"
    )
    parser.add_argument(
        "--extra",
        action="append",
        default=[],
        help="additional symbol to export, e.g. one defined by the shim itself",
    )
    parser.add_argument("archives", nargs="+")
    args = parser.parse_args(argv)

    functions, data = set(), set()
    for archive in args.archives:
        for name, is_function in defined_symbols(args.nm, archive):
            if not name.startswith(C_API_PREFIX):
                continue
            (functions if is_function else data).add(name)

    functions.update(args.extra)
    data -= functions

    lines = ["; Generated by gen_msvc_exports.py - do not edit.", "EXPORTS"]
    lines += [f"    {name}" for name in sorted(functions)]
    # Exported variables have to be marked, or the linker exports the address of
    # the address.
    lines += [f"    {name} DATA" for name in sorted(data)]

    output = pathlib.Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"{output}: {len(functions)} functions, {len(data)} data symbols")
    return 0


if __name__ == "__main__":
    sys.exit(main())
