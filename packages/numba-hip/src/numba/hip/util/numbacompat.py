"""
Utility functions for post-processing Numba-generated LLVM IR so that it is compatible
with the ROCm compilers used by the Numba HIP backend.
"""

import re

_p_typed_ptr = re.compile(pattern=r"\w+\*+")

# Parse alloca instruction; more details: https://llvm.org/docs/LangRef.html#alloca-instruction
_p_alloca = re.compile(r"\s*%(?P<ident>.*[^ ])\s*=\s*alloca\s+(?P<parms>.+)")


def _alloca_addrspace_correction(llvm_ir: str) -> str:
    """Correct alloca statements without `addrspace(5)` parameter.

    Rewrites llvm_ir such that `alloca`'s go into `addrspace(5)` (amdgpu private address space, AS5)
    and are then `addrspacecast` back to `addrspace(0)`. Alloca into AS5 is a requirement of
    the amdgpu datalayout specification.

    Example:

        ```llvm
        %.34 = alloca { ptr, i32, i32 }, align 8
        ```

        is transformed to:

        ```llvm
        %.34__tmp =  alloca { ptr, i32, i32 }, align 8, addrspace(5)
        %.34 = addrspacecast ptr addrspace(5) %.34__tmp to ptr addrspace(0)
        ```

    More details on amdgpu address spaces:

        https://llvm.org/docs/AMDGPUUsage.html#address-spaces
    """
    global _p_alloca
    lines = llvm_ir.splitlines(keepends=True)
    mangle = "__numba_hip_tmp"
    new_ir = []
    for line in lines:
        # pluck lines containing alloca
        if (
            "alloca " in line and "addrspace(" not in line
        ):  # inputs might be already in correct shape
            result = _p_alloca.match(line)
            if result:
                ident: str = result.group("ident")
                parms: str = result.group("parms")
                if ident.startswith('"'):  # quoted
                    tmp_ident = '"' + ident.strip('"') + mangle + '"'
                else:
                    tmp_ident = ident + mangle
                new_ir.append(
                    f"%{tmp_ident} = alloca {parms}, addrspace(5)\n"
                )  # tmp_ident is a ptr
                new_ir.append(
                    f"%{ident} = addrspacecast ptr addrspace(5) %{tmp_ident} to ptr addrspace(0)\n"
                )
            else:
                new_ir.append(line)
        else:
            new_ir.append(line)
    return "".join(new_ir)


def _replace_sext_ptr_by_ptrtoint_ptr(llvm_ir: str) -> str:
    """Fix sext application to pointers where ptrtoint would be correct.

    Transforms expressions like

        %val = sext ptr null to i32
        %val = sext ptr null to i64

    that may be generated by Numba Core to

        %val = ptrtoint ptr null to i32
        %val = ptrtoint ptr null to i64
    """
    return llvm_ir.replace("sext ptr null to i", "ptrtoint ptr null to i")


def _replace_typed_by_opaque_ptr(llvm_ir: str) -> str:
    """Replaced typed pointers by opaque 'ptr'.

    Newer LLVM compilers (>= LLVM 16, like those shipped by ROCm),
    only support opaque pointers. Typed pointers are not supported.

    More details:

        https://releases.llvm.org/15.0.0/docs/OpaquePointers.html
    """
    global _p_typed_ptr
    if (
        "*" in llvm_ir
    ):  # note: significant optimization as _TYPED_PTR.sub is costly
        return _p_typed_ptr.sub(string=llvm_ir, repl="ptr")
    return llvm_ir


def postprocess_numba_llvm_ir(llvmir: str) -> str:
    result = llvmir
    for op in (
        _alloca_addrspace_correction,
        _replace_sext_ptr_by_ptrtoint_ptr,
        _replace_typed_by_opaque_ptr,
    ):
        result = op(result)
    return result
